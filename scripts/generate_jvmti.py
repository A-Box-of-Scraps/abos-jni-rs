"""Generate declaration-only JVMTI 25 bindings from a local JDK's jvmti.h.

This deliberately handles the small grammar of the generated JDK header, not
arbitrary C. Unknown declarations fail rather than silently producing bindings.
No JDK or generator is needed when building the checked-in Rust sources.
"""

import argparse
import os
import re
import subprocess
from pathlib import Path

import jvmti_versions

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/abos-jvmti-sys/src"
NOTICE = "// Generated by scripts/generate_jvmti.py from JVMTI 25 declarations.\n"
IMPORTS = "use super::*;\n"
C_TYPES = {"void": "c_void", "char": "c_char", "unsigned char": "u8", "unsigned int": "u32"}


def rust_type(declaration):
    parts = declaration.strip().split("*")
    base = parts[0].strip()
    constant = base.startswith("const ")
    base = base.removeprefix("const ").removeprefix("struct ")
    if base not in C_TYPES and not re.fullmatch(r"[A-Za-z_]\w*", base):
        raise ValueError(f"Unsupported C type: {declaration}")
    result = C_TYPES.get(base, base)
    for index, qualifier in enumerate(parts[1:]):
        if qualifier.strip():
            raise ValueError(f"Unsupported pointer qualifier: {declaration}")
        result = f"*{'const' if constant and index == 0 else 'mut'} {result}"
    return result


def field(declaration):
    match = re.fullmatch(r"(.+?[\s*])(\w+)", declaration.strip())
    if not match:
        raise ValueError(f"Unsupported field: {declaration}")
    ty, name = match.groups()
    return ("r#type" if name == "type" else name), rust_type(ty)


def function(result, arguments, *, named=True):
    params = []
    variadic = False
    for arg in arguments.split(","):
        arg = arg.strip()
        if arg in ("", "void"):
            continue
        if arg == "...":
            params.append("...")
            variadic = True
        else:
            name, ty = field(arg)
            params.append(f"{name}: {ty}" if named else ty)
    # C variadic functions use cdecl even where JNICALL is stdcall.
    abi = "C" if variadic else "system"
    output = "" if result.strip() == "void" else f" -> {rust_type(result)}"
    return f'Option<unsafe extern "{abi}" fn({", ".join(params)}){output}>'


def records(source):
    pattern = r"(?:typedef\s+)?(struct|union)\s*(\w+)?\s*\{([^{}]*)\}\s*(\w+)?\s*;"
    result = []
    for match in re.finditer(pattern, source, re.DOTALL):
        kind, tag, body, alias = match.groups()
        name = tag or alias
        if name == "jvmtiCapabilities":
            continue
        derive = "Clone, Copy" if kind == "union" else "Clone, Copy, Debug, Default"
        lines = [f"#[repr(C)]\n#[derive({derive})]\npub {kind} {name} {{"]
        for declaration in body.split(";"):
            if not declaration.strip():
                continue
            fn = re.fullmatch(r"\s*(\w+)\s*\(JNICALL\s*\*(\w+)\)\s*\((.*?)\)\s*", declaration, re.DOTALL)
            if fn:
                ret, member, params = fn.groups()
                ty = function(ret, params, named=False)
            else:
                member, ty = field(declaration)
            lines.append(f"pub {member}: {ty},")
        lines.append("}\n")
        if alias and alias != name:
            lines.append(f"pub type {alias} = {name};\n")
        result.append((name, "\n".join(lines)))
    return result


def enum_alias(name, signed):
    if signed:
        return f"pub type {name} = i32;"
    # MSVC uses signed int for these enums; GCC and Clang's non-MSVC ABI use unsigned int.
    return (
        f'#[cfg(target_env = "msvc")]\npub type {name} = i32;\n#[cfg(not(target_env = "msvc"))]\npub type {name} = u32;'
    )


def generate(header):
    source = re.sub(r"/\*.*?\*/", "", header, flags=re.DOTALL)
    version = re.search(r"JVMTI_VERSION\s*=\s*0x30000000\s*\+\s*\((\d+)\s*\*", source)
    if not version or version[1] != "25":
        raise ValueError("Generation requires a JVMTI 25 header")
    capabilities = re.search(r"typedef struct\s*\{([^{}]+)\}\s*jvmtiCapabilities;", source)
    if capabilities is None:
        raise ValueError("Missing or unsupported jvmtiCapabilities declaration")
    constants = []
    for body, alias in re.findall(r"(?:typedef\s+)?enum\s*\{([^}]+)\}\s*(\w*)\s*;", source):
        signed = bool(re.search(r"=\s*-", body))
        ty = alias or "jint"
        if alias:
            constants.append(enum_alias(alias, signed))
        for entry in body.split(","):
            entry = entry.strip()
            if not entry:
                continue
            name, value = entry.split("=", 1)
            constants.append(f"pub const {name.strip()}: {ty} = {value.strip()};")
    callbacks = []
    for result, name, args in re.findall(r"typedef\s+(\w+)\s*\(JNICALL\s*\*(\w+)\)\s*\((.*?)\)\s*;", source, re.DOTALL):
        callbacks.append(f"pub type {name} = {function(result, args)};\n")
    declarations = dict(records(source))
    if len(declarations) != 24 or len(callbacks) != 48:
        raise ValueError(f"Unexpected header shape: {len(declarations)} records, {len(callbacks)} callbacks")
    table = declarations.pop("jvmtiInterface_1_")
    event_table = declarations.pop("jvmtiEventCallbacks")
    fields = [
        (name, int(width)) for name, width in re.findall(r"unsigned int\s+(\w*)\s*:\s*(\d+)\s*;", capabilities[1])
    ]
    if sum(width for _, width in fields) != 128:
        raise ValueError("Unexpected capabilities layout")
    methods = []
    bit = 0
    for name, width in fields:
        if name:
            if width != 1:
                raise ValueError("Only boolean capabilities are supported")
            methods.append(f"capability!({name}, set_{name}, {bit});")
        bit += width
    return {
        "api/constants.rs": (
            "#![allow(clippy::unreadable_literal, clippy::identity_op, clippy::erasing_op, "
            'reason = "Preserve header literals and version arithmetic.")]\n' + IMPORTS + "\n".join(constants)
        ),
        "api/callbacks.rs": IMPORTS + "\n".join(callbacks) + event_table,
        "api/types.rs": IMPORTS + "\n".join(declarations.values()),
        "api/interface.rs": IMPORTS + jvmti_versions.annotate_table(table),
        "api/compatibility.rs": jvmti_versions.compatibility(event_table, [name for name, _ in fields if name]),
        "internal/capability_bits.rs": "use super::jvmtiCapabilities;\nimpl jvmtiCapabilities {\n"
        + "\n".join(methods)
        + "\n}",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, default=Path(os.environ.get("JAVA_HOME", "")) / "include/jvmti.h")
    parser.add_argument("--check", action="store_true", help="Check that the committed declarations are up to date")
    args = parser.parse_args()
    rustfmt = ["rustfmt", "--edition", "2024", "--config-path", str(ROOT / "rustfmt.toml")]
    for name, content in generate(args.header.read_text()).items():
        formatted = subprocess.run(
            rustfmt,
            input=NOTICE + content + "\n",
            text=True,
            capture_output=True,
            check=True,
        ).stdout
        path = OUTPUT / name
        if args.check:
            if path.read_text() != formatted:
                raise SystemExit(f"Stale bindings: {path}")
        else:
            path.write_text(formatted)


if __name__ == "__main__":
    main()
