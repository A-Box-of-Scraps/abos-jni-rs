use crate::{BindingInfo, Bindings, Module, ModuleBinding, ModuleEvent, Result, TypeMap};
use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path};

const HEADER: &str = "// Generated by abos-jbindgen. Do not edit manually.\n\n";

const fn empty_module(name: String) -> Module {
	Module {
		name,
		children: BTreeMap::new(),
		bindings: Vec::new(),
		use_statements: Vec::new(),
	}
}

pub fn assemble(
	modules: Vec<ModuleBinding>,
	generate_jni_init: bool,
	input_type_mappings: Vec<(String, String)>,
	root_path: String,
) -> Bindings {
	let mut roots: BTreeMap<String, Module> = BTreeMap::new();
	for binding in modules {
		let mut path: Vec<String> = binding.module_path.clone();
		if path.is_empty() {
			path.push(String::new());
		}
		let mut level: &mut BTreeMap<String, Module> = &mut roots;
		for segment in &path[..path.len() - 1] {
			level = &mut level
				.entry(segment.clone())
				.or_insert_with(|| empty_module(segment.clone()))
				.children;
		}
		let name: String = path.last().cloned().unwrap_or_default();
		let module: &mut Module = level.entry(name.clone()).or_insert_with(|| empty_module(name));
		for import in binding.use_statements {
			if !module.use_statements.contains(&import) {
				module.use_statements.push(import);
			}
		}
		module.bindings.push(BindingInfo {
			rust_type_name: binding.rust_type_name,
			rust_api_type_name: binding.rust_api_type_name,
			code: binding.binding_code,
			java_type_name: binding.java_type_name,
			package: binding.package,
		});
	}
	Bindings {
		root_modules: roots,
		generate_jni_init,
		input_type_mappings,
		root_path,
	}
}

pub fn walk<F: FnMut(&Module, ModuleEvent)>(module: &Module, callback: &mut F) {
	callback(module, ModuleEvent::BeginModule);
	for child in module.children.values() {
		walk(child, callback);
	}
	callback(module, ModuleEvent::EndModule);
}

fn initialization(bindings: &[BindingInfo], children: impl Iterator<Item = impl AsRef<str>>) -> String {
	let mut output: String = String::from(
		"/// Initialize the Java bindings in this module.\npub fn jni_init(env: &::jni::Env, loader: &::jni::refs::LoaderContext) -> ::jni::errors::Result<()> {\n",
	);
	for binding in bindings {
		writeln!(output, "    let _ = {}::get(env, loader)?;", binding.rust_api_type_name).expect("writing to String");
	}
	for child in children {
		writeln!(output, "    {}::jni_init(env, loader)?;", child.as_ref()).expect("writing to String");
	}
	output.push_str("    Ok(())\n}\n");
	output
}

fn contents(module: &Module) -> String {
	let mut output = String::new();
	for import in &module.use_statements {
		writeln!(output, "{import}").expect("writing to String");
	}
	for binding in &module.bindings {
		writeln!(output, "\n{}", binding.code).expect("writing to String");
	}
	output
}

fn root_contents(bindings: &Bindings) -> String {
	let mut output: String = bindings.root_modules.get("").map(contents).unwrap_or_default();
	if bindings.generate_jni_init && !bindings.is_empty() {
		let defaults: &[BindingInfo] = bindings.root_modules.get("").map_or(&[], |module| &module.bindings);
		output.push_str(&initialization(
			defaults,
			bindings.root_modules.keys().filter(|name| !name.is_empty()),
		));
	}
	output
}

pub fn render(bindings: &Bindings) -> String {
	fn render_module(module: &Module, init: bool) -> String {
		let mut output = String::new();
		writeln!(output, "pub mod {} {{", module.name).expect("writing to String");
		let mut body: String = contents(module);
		for child in module.children.values() {
			body.push_str(&render_module(child, init));
		}
		if init {
			body.push_str(&initialization(&module.bindings, module.children.keys()));
		}
		for line in body.lines() {
			writeln!(output, "    {line}").expect("writing to String");
		}
		output.push_str("}\n");
		output
	}
	let mut output: String = String::from(HEADER);
	for (name, module) in &bindings.root_modules {
		if !name.is_empty() {
			output.push_str(&render_module(module, bindings.generate_jni_init));
		}
	}
	output.push_str(&root_contents(bindings));
	output
}

pub fn write_tree(bindings: &Bindings, root: &Path) -> Result<()> {
	fn write_module(module: &Module, root: &Path, init: bool) -> Result<()> {
		let directory: std::path::PathBuf = root.join(&module.name);
		fs::create_dir_all(&directory)?;
		let mut output: String = String::from(HEADER);
		for child in module.children.values() {
			writeln!(output, "pub mod {};", child.name).expect("writing to String");
			write_module(child, &directory, init)?;
		}
		output.push_str(&contents(module));
		if init {
			output.push_str(&initialization(&module.bindings, module.children.keys()));
		}
		fs::write(directory.join("mod.rs"), output)?;
		Ok(())
	}
	fs::create_dir_all(root)?;
	let mut output: String = String::from(HEADER);
	for (name, module) in &bindings.root_modules {
		if name.is_empty() {
			continue;
		}
		writeln!(output, "pub mod {name};").expect("writing to String");
		write_module(module, root, bindings.generate_jni_init)?;
	}
	output.push_str(&root_contents(bindings));
	fs::write(root.join("mod.rs"), output)?;
	Ok(())
}

pub fn type_map(bindings: &Bindings, root: Option<&str>) -> TypeMap {
	let mut map = TypeMap::new();
	map.merge(bindings.input_type_mappings.clone());
	let mut path: Vec<String> = Vec::new();
	bindings.walk(&mut |module, event| {
		if event == ModuleEvent::EndModule {
			if !module.name.is_empty() {
				path.pop();
			}
			return;
		}
		if !module.name.is_empty() {
			path.push(module.name.clone());
		}
		for binding in &module.bindings {
			let mut rust_name: String = root.unwrap_or(&bindings.root_path).to_owned();
			for segment in &path {
				write!(rust_name, "::{segment}").expect("writing to String");
			}
			write!(rust_name, "::{}", binding.rust_type_name).expect("writing to String");
			map.insert(format!("{}.{}", binding.package, binding.java_type_name), rust_name);
		}
	});
	map
}

pub fn write_type_map(map: &TypeMap, path: &Path) -> Result<()> {
	let mut entries: Vec<(&String, &String)> = map.iter().collect();
	entries.sort_by_key(|(java, _)| *java);
	let mut output = String::new();
	for (java, rust) in entries {
		writeln!(output, "{rust} => \"{java}\"").expect("writing to String");
	}
	fs::write(path, output)?;
	Ok(())
}
